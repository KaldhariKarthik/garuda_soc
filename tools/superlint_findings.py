#!/usr/bin/env python3
"""superlint_findings.py - one entry per JasperGold Superlint finding (D-40, 2026-11-20).

    python3 tools/superlint_findings.py <superlint_violations.txt> > flow/2_static/superlint/chip/findings.tsv

Superlint's 77 findings of 2026-11-10 were explained in prose, by class, in RESULTS.md. D-40 asks
for one entry per finding, so this tool reads the tool's report and writes one row per finding:

    tag <TAB> file:line <TAB> instance <TAB> class <TAB> reason

The class comes from the rules below (tag and file), each the reading written in RESULTS.md.
A finding no rule matches is written with class OPEN, which tools/waiver_audit.py counts as
unjustified: a new finding is never classified by default.
"""
import re, sys

# (tag regex, file regex, class, reason)
RULES = [
    (r"BUS_IS_FLOT", r"rtl/soc/garuda_chip_top\.sv", "PAD_TRISTATE",
     "a tristate or open-drain pin floats while its enable is 0 (JTAG TDO per IEEE 1149.1, I2C open drain with board pull-ups, GPIO, SPI slave MISO); pad cells replace the model"),
    # dead code, own RTL
    (r"BLK_NO_RCHB", r"rtl/mem/ahb_mem_slave_if\.sv", "PARAM_INSTANCE",
     "the boot ROM instance (WRITABLE=0) never fills the write buffer; live in ISRAM and DSRAM"),
    (r"BLK_NO_RCHB", r"rtl/ahb2apb/ahb2apb_apb_fsm\.sv", "PARAM_INSTANCE",
     "APB_DIV gives every window a divider of 0 and there are 12 windows: the extra-wait countdown and window index 12+ are unused"),
    (r"BLK_NO_RCHB", r"rtl/clic/clic_select\.sv", "TIE_OFF",
     "ID 0 and the IDs with no source are masked out of the candidates (CLIC ID mask)"),
    (r"BLK_NO_RCHB", r"rtl/(ahb2apb/(ahb2apb_bridge|brg_ahb_fsm|apb_phase_fsm)|ahb/ahb_(dflt_slave|slave_mux|default_slave)|core/(dport_master|d_port_ahb_master|alu_unit|alu|csr_file|decode_control)|dma/(dma_engine|dma_eng_fsm))\.sv", "DEFAULT_ARM",
     "the default arm of a case whose items cover every value that can occur; kept so an illegal state or encoding returns to a safe one"),
    # dead code, vendored IP
    (r"BLK_NO_RCHB", r"rtl/third_party/pulp/axi_spi_master/", "VENDOR_UNUSED_MODE",
     "quad and dual SPI paths of the vendored SPI master: GARUDA uses single-bit SPI (SPIM spec); MODE state is SPIM-2"),
    (r"BLK_NO_RCHB", r"rtl/third_party/pulp/apb_spi_master/", "DEFAULT_ARM",
     "default arm of the vendored transmit-side state machine"),
    (r"BLK_NO_RCHB", r"rtl/third_party/pulp/apb_uart_sv/", "VENDOR_UNUSED_MODE",
     "vendored UART: default arms of its state machines, the disabled branches (cfg_en_i tied 1) and the character timeout (CTI_i tied 0)"),
    (r"BLK_NO_RCHB", r"rtl/third_party/pulp/apb_gpio/", "VENDOR_UNUSED_MODE",
     "vendored GPIO registers of pins 32 to 63; GARUDA uses 2 pins"),
    (r"BLK_NO_RCHB", r"rtl/third_party/opencores/i2c/", "TIE_OFF",
     "the filter counter's reset when the core is disabled: the wrapper ties ena to 1"),
    # overflow
    (r"(ASG|EXP)_AR_OVFL", r"rtl/core/(alu_unit|alu|branch_predict|branch_unit|ex_stage|garuda_pc_gen)\.sv", "ISA_MODULO",
     "RV32I defines address and ALU arithmetic modulo 2^32: a target past 0xFFFF_FFFC wraps, ADD and SUB ignore the carry"),
    (r"(ASG|EXP)_AR_OVFL", r"rtl/(core/csr_file|timers/mtime)\.sv", "COUNTER_64",
     "64-bit counters (mcycle, minstret, mtime) wrap at 2^64 as the privileged spec says"),
    (r"SHF_IS_OVFL", r"rtl/(core/(alu_unit|alu)|dsu/barrel_shifter)\.sv", "SHIFT",
     "a left shift drops the bits shifted out, as SLL and the DSU shift define"),
    (r"(ASG|EXP)_(IS|AR)_OVFL", r"rtl/(core/(alu_unit|alu|mul32)|dsu/(barrel_shifter|mac_unit))\.sv", "SIGN_SAME_WIDTH",
     "a signed value stored into an unsigned one of the same width (or the reverse); the bits are kept, which is what the line wants"),
    (r"(ASG|EXP)_AR_OVFL", r"rtl/dsu/kogge_stone_49\.sv", "GUARD_BIT",
     "the MAC's 49-bit adder: bit 48 is the guard bit; overflow is detected from bits 48 and 47 and saturated"),
    (r"SHF_IS_OVFL|(ASG|EXP)_(IS|AR)_OVFL", r"rtl/dma/dma_apb_slave\.sv", "EXCLUDED_INDEX",
     "a channel number of 6 or 7 shifts the 1 out of the 6-bit select; those numbers are excluded before the select is used (chan_rgn)"),
    (r"(ASG|EXP)_(IS|AR)_OVFL", r"rtl/third_party/pulp/apb_uart_sv/", "VENDOR_COUNTER",
     "the vendored UART's 3-bit bit counter wraps only if software changes the character length mid-frame"),
    (r"(ASG|EXP)_(IS|AR)_OVFL", r"rtl/third_party/pulp/apb_spi_master/", "VENDOR_COUNTER",
     "with a receive count of 0 the subtraction wraps and the count interrupt does not fire: right for a count of 0"),
]

ROW = re.compile(r"^\[\d+\]\s+(?:Error|Warning|Info)\s+(\S+)\s+\"(.*?)\"\s+(\S+)\s*:(\d+)\s+(\S+)")


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    print("# tag\tfile:line\tinstance\tclass\treason   (generated by tools/superlint_findings.py; OPEN = no class: unjustified)")
    n = op = 0
    for ln in open(sys.argv[1], errors="replace"):
        m = ROW.match(ln.strip())
        if not m:
            continue
        tag, msg, f, line, inst = m.groups()
        cls, why = "OPEN", "no class: " + msg
        for tr, fr, c, w in RULES:
            if re.search(tr, tag) and re.search(fr, f):
                cls, why = c, w
                break
        n += 1
        op += cls == "OPEN"
        print("%s\t%s:%s\t%s\t%s\t%s" % (tag, f, line, inst, cls, why))
    sys.stderr.write("superlint_findings: %d findings, %d OPEN\n" % (n, op))
    return 0


if __name__ == "__main__":
    sys.exit(main())
