#!/usr/bin/env python3
"""build_archtest.py -- build riscv-arch-test 3.10.0 for GARUDA (plan 5.4).

    python3 tools/archtest/build_archtest.py

Suites (DN-ISA): rv32i_m/I, the multiply half of rv32i_m/M (Zmmul: mul, mulh,
mulhsu, mulhu -- DIV/REM are illegal on GARUDA by design, N/A unless the misa
ruling says M=1), rv32i_m/Zifencei, rv32i_m/privilege. Each test is compiled
with its own RVTEST_CASE defines, the GARUDA target env (tb/core/archtest/env),
and turned into a tb_boot hex; then tb/core/run/archtest.toml is written: each
test runs on tb_boot, dumps its signature, and tools/archtest/sigcheck.py
compares it with Spike's.
"""
import glob, json, os, re, subprocess, sys
R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
T = os.environ.get("GARUDA_TOOLS", os.path.expanduser("~/tools"))
AT = os.path.join(T, "src", "riscv-arch-test-3.10.0", "riscv-test-suite")
CC = os.path.join(os.environ.get("RISCV_BIN", f"{T}/riscv/bin"), os.environ.get("RISCV_PREFIX", "riscv-none-elf-"))
OUT = os.path.join(R, "logs", "core", "raw", "archtest_build")
os.makedirs(OUT, exist_ok=True)
SUITES = {"I": None, "M": r"^mul", "Zifencei": None, "privilege": None}
tests, fails = [], []
for suite, keep in SUITES.items():
    for src in sorted(glob.glob(f"{AT}/rv32i_m/{suite}/src/*.S")):
        name = f"{suite}-{os.path.splitext(os.path.basename(src))[0]}"
        if keep and not re.search(keep, os.path.basename(src)):
            continue
        txt = open(src).read()
        defs = set(re.findall(r"def\s+([A-Za-z_0-9]+)\s*=\s*([A-Za-z_0-9]+)", txt))
        elf, bin_, hexf = (os.path.join(OUT, name + e) for e in (".elf", ".bin", ".hex"))
        cmd = [CC + "gcc", "-march=rv32i_zmmul_zicsr_zifencei", "-mabi=ilp32", "-static", "-mcmodel=medany",
               "-fvisibility=hidden", "-mno-relax", "-nostdlib", "-nostartfiles", "-T", f"{R}/tb/core/archtest/env/link.ld",
               "-I", f"{R}/tb/core/archtest/env", "-I", f"{AT}/env", "-DXLEN=32",
               *[f"-D{k}={v}" for k, v in sorted(defs)], src, "-o", elf]
        p = subprocess.run(cmd, capture_output=True, text=True)
        if p.returncode:
            fails.append((name, p.stderr.strip().splitlines()[-1] if p.stderr.strip() else "?"))
            continue
        subprocess.run([CC + "objcopy", "-O", "binary", elf, bin_], check=True)
        subprocess.run([sys.executable, f"{R}/tools/elf2hex.py", bin_, hexf], check=True, capture_output=True)
        syms = dict((l.split()[2], l.split()[0]) for l in subprocess.run([CC + "nm", elf], capture_output=True,
                    text=True).stdout.splitlines() if len(l.split()) == 3)
        tests.append((name, os.path.relpath(hexf, R), os.path.relpath(elf, R), syms["begin_signature"],
                      syms["end_signature"], syms["tohost"]))
q = json.dumps
m = ['''# Plan 5.4: riscv-arch-test 3.10.0 on GARUDA, signatures against Spike.
# GENERATED by tools/archtest/build_archtest.py -- do not edit by hand.
# Run: make -f flow/mk/track_a_run.mk core_archtest
[suite]
block = "core"
name  = "archtest"
kind  = "prog"
xfail = "tb/core/run/xfail.tsv"

[bench]
flist = "tb/soc/filelist_boot_mem2m.f"
top   = "tb_boot"

[defaults]
marker   = 'TOHOST=1 -> PASSED'
timeout  = 900
require  = ['AHB-PROTOCOL: iport=0 dport=0']
''']
for name, hexf, elf, b, e, th in tests:
    m.append(f'''[[test]]
name = {q(name)}
hex  = {q(hexf)}
plusargs = {q(["+MAXCYC=3000000", "+QUIET", f"+TOHOST={th}", "+SIGFILE={raw}/{name}.signature", f"+SIGBEGIN={b}", f"+SIGEND={e}"])}
post = {q(["python3", "{root}/tools/archtest/sigcheck.py", "{root}/" + elf, "{raw}/{name}.signature"])}
''')
open(f"{R}/tb/core/run/archtest.toml", "w").write("\n".join(m))
print(f"built {len(tests)} tests, {len(fails)} failed to build")
for f in fails:
    print("  BUILD-FAIL", *f)
