#!/usr/bin/env python3
"""gen_t_cov_dsu.py -- write sw/tests/t_cov_dsu.S (Track A coverage closure).

The DSU inside the core: every op on every accumulator, operand patterns that
move every accumulator bit both ways, MACSAT overflow, a real 48-bit
accumulate overflow (a 65536-iteration MACDOT loop -- the only way to get the
accumulator past 2^47, see DSU_gen.clamp_walk_tests), and the read-to-clear
dsu_ovf CSR (0xBC0). Every readback and every dsu_ovf read is checked against
ArchDSU, the timeless independent oracle in tools/golden/DSU_Golden.py, so the
program checks results, not only that it ran.

    python3 tools/gen/gen_t_cov_dsu.py            (rewrites sw/tests/t_cov_dsu.S)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "golden"))
from DSU_Golden import (ArchDSU, asm, asm_shift, MAC_SEL, MACSUB, MACABS, MACDOT,  # noqa: E402
                        MACLOAD, MACCLEAR, MACSAT, MACRD_LO, MACRD_HI, ACC_FX, ACC_FY,
                        ACC_MAG, MASK32)

OUT = os.path.join(HERE, "..", "..", "sw", "tests", "t_cov_dsu.S")
NAMES = {MAC_SEL: "MAC_SEL", MACSUB: "MACSUB", MACABS: "MACABS", MACDOT: "MACDOT",
         MACLOAD: "MACLOAD", MACCLEAR: "MACCLEAR", MACSAT: "MACSAT",
         MACRD_LO: "MACRD_LO", MACRD_HI: "MACRD_HI"}
ACCS = {ACC_FX: "FX", ACC_FY: "FY", ACC_MAG: "MAG"}

arch = ArchDSU()
lines = []
nchk = 0


def emit(s=""):
    lines.append(s)


def op(f5, acc, rs1=0, rs2=0):
    """A compute / load / clear / sat op (no rd write)."""
    emit(f"    li      a1, 0x{rs1 & MASK32:08X}")
    emit(f"    li      a2, 0x{rs2 & MASK32:08X}")
    emit(f"    .insn r 0x0b, 0, {(f5 << 2) | acc}, zero, a1, a2      # {NAMES[f5]} {ACCS[acc]}")
    arch.step(asm(f5, acc, 0, 11, 12), rs1, rs2)


def check(code, want):
    """rd (t0) must equal the oracle's value."""
    global nchk
    nchk += 1
    emit(f"    li      t6, 0x{want & MASK32:08X}")
    emit(f"    li      a0, {code}")
    emit("    bne     t0, t6, fail")


def readback(f5, acc):
    r = arch.step(asm(f5, acc, 5, 0, 0))
    emit(f"    .insn r 0x0b, 0, {(f5 << 2) | acc}, t0, zero, zero      # {NAMES[f5]} {ACCS[acc]} -> t0")
    check(3 if f5 == MACRD_LO else 5, r["rd_data"])


def shift(acc, amt, left):
    r = arch.step(asm_shift(acc, amt, left, 5))
    imm = (left << 8) | (acc << 6) | (amt & 0x3F)
    emit(f"    .insn i 0x0b, 1, t0, zero, {imm}      # MACSHIFT {ACCS[acc]} {'<<' if left else '>>'} {amt}")
    check(7, r["rd_data"])


def read_ovf():
    """csrr dsu_ovf: returns the sticky flag and clears it (read-to-clear)."""
    want = 1 if arch.overflow_sticky else 0
    arch.overflow_sticky = False
    emit("    csrr    t0, 0xBC0                   # dsu_ovf (read clears)")
    check(9, want)


emit("# =============================================================================")
emit("# t_cov_dsu.S -- GENERATED by tools/gen/gen_t_cov_dsu.py; do not edit by hand.")
emit("# The DSU inside the core: all 10 ops x 3 accumulators, accumulator bit")
emit("# patterns both ways, MACSAT overflow, a 48-bit accumulate overflow (65536")
emit("# MACDOTs), dsu_ovf read-to-clear. Expected values from ArchDSU (independent")
emit("# oracle). Fail codes: 3 RD_LO, 5 RD_HI, 7 MACSHIFT, 9 dsu_ovf mismatch.")
emit("# =============================================================================")
emit('    .section .text.init, "ax"')
emit("    .global _start")
emit("_start:")
emit("    lla     sp, stack_top")

for acc in (ACC_FX, ACC_FY, ACC_MAG):
    emit(f"    # ---- accumulator {ACCS[acc]} ----")
    op(MACCLEAR, acc)
    readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    op(MACLOAD, acc, 0x80000000)                         # acc = sign-extended -2^31
    readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    op(MAC_SEL, acc, 0x0003, 0x0004)
    op(MACSUB, acc, 0x0003, 0x0004)
    op(MACABS, acc, 0x8000, 0x8000)                      # |-32768| * |-32768| = 2^30
    readback(MACRD_LO, acc)
    op(MACDOT, acc, 0x00020003, 0x00040005)
    readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    op(MACSAT, acc)                                      # in range: unchanged
    shift(acc, 4, 0); shift(acc, 12, 1)
    for pat in (0x55555555, 0xAAAAAAAA, 0x7FFFFFFF, 0x10000000):
        op(MACLOAD, acc, pat)
        readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    op(MAC_SEL, acc, 0x7FFF, 0x7FFF)                     # 0x10000000 + 2^30-ish
    op(MACLOAD, acc, 0x7FFFFFFF)
    op(MAC_SEL, acc, 0x7FFF, 0x7FFF)                     # now > 2^31 - 1
    op(MACSAT, acc)                                      # clamps, sets overflow
    readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    read_ovf()                                           # 1, and clears
    read_ovf()                                           # 0
    op(MACCLEAR, acc)
    readback(MACRD_LO, acc); readback(MACRD_HI, acc)

# ---- real 48-bit accumulate overflows: 65536 maximal MACDOTs per accumulator ---
# MAG and FX overflow upward: 65536 x (+2^31) = 2^47 > 2^47-1. FY overflows
# downward: each op adds 2 x (-32768 x 32767) = -2^31 + 2^16, so 65536 ops stop
# 2^32 short of -2^47; 65540 ops pass it. The oracle decides; the dsu_ovf reads
# after each loop check that it really overflowed.
# The overflowing op directly followed by `csrr dsu_ovf` is t_dsu_ovf_raw
# (tools/gen/gen_t_cov_dsu.py --ovf-raw, DSU-14); here it is in the loop.
LAST = "--ovf-raw" in sys.argv
if LAST:
    OUT = os.path.join(HERE, "..", "..", "sw", "tests", "t_dsu_ovf_raw.S")
for acc, rs1, rs2, what, n, last_then_csr in ((ACC_MAG, 0x80008000, 0x80008000, "up", 65536, LAST),
                                              (ACC_FX,  0x80008000, 0x80008000, "up", 65536, False),
                                              (ACC_FY,  0x80008000, 0x7FFF7FFF, "down", 65540, False)):
    emit(f"    # ---- 48-bit accumulate overflow on {ACCS[acc]} ({what}): {n} x MACDOT(0x{rs1:08X}, 0x{rs2:08X}) ----")
    op(MACCLEAR, acc)
    read_ovf()
    emit(f"    li      a1, 0x{rs1:08X}")
    emit(f"    li      a2, 0x{rs2:08X}")
    emit(f"    li      s1, {n - 1 if last_then_csr else n}")
    emit("1:  .insn r 0x0b, 0, %d, zero, a1, a2      # MACDOT %s" % ((MACDOT << 2) | acc, ACCS[acc]))
    emit("    addi    s1, s1, -1")
    emit("    bnez    s1, 1b")
    for _ in range(n - 1 if last_then_csr else n):
        arch.step(asm(MACDOT, acc, 0, 11, 12), rs1, rs2)
    if last_then_csr:
        assert not arch.overflow_sticky, f"{ACCS[acc]} overflowed before the last op"
        emit("    .insn r 0x0b, 0, %d, zero, a1, a2      # MACDOT %s: the overflowing one" % ((MACDOT << 2) | acc, ACCS[acc]))
        arch.step(asm(MACDOT, acc, 0, 11, 12), rs1, rs2)
        assert arch.overflow_sticky, f"{ACCS[acc]} last op did not overflow"
        read_ovf()                                       # back-to-back with the overflowing MACDOT: 1
        read_ovf()                                       # cleared: 0
        readback(MACRD_LO, acc); readback(MACRD_HI, acc)
    else:
        readback(MACRD_LO, acc); readback(MACRD_HI, acc)
        assert arch.overflow_sticky, f"{ACCS[acc]} loop did not overflow"   # the test's own claim
        read_ovf()                                       # the accumulate overflow (must read 1)
    read_ovf()
    op(MACCLEAR, acc)
    readback(MACRD_HI, acc)

emit("    li      a0, 1")
emit("    j       done")
emit("fail:")
emit("done:")
emit("    lla     t0, tohost")
emit("    li      t1, 1")
emit("    beq     a0, t1, 2f")
emit("    slli    a0, a0, 1")
emit("    ori     a0, a0, 1")
emit("2:  sw      a0, 0(t0)")
emit("1:  j       1b")
emit("    .section .data")
emit("    .align 4")
emit("stack:  .space 256")
emit("stack_top:")
text = "\n".join(lines) + "\n"
if LAST:
    text = text.replace("# t_cov_dsu.S -- GENERATED by tools/gen/gen_t_cov_dsu.py;",
                        "# t_dsu_ovf_raw.S -- GENERATED by tools/gen/gen_t_cov_dsu.py --ovf-raw;", 1)
    text = text.replace("# The DSU inside the core:",
                        "# DSU-14: t_cov_dsu with the overflowing MACDOT on MAG issued last, directly\n"
                        "# followed by `csrr dsu_ovf` (architecturally it reads 1). Otherwise as t_cov_dsu:\n"
                        "# The DSU inside the core:", 1)
open(OUT, "w").write(text)
print(f"wrote {os.path.relpath(OUT)}: {nchk} checks against ArchDSU")
