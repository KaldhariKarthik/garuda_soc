#!/usr/bin/env python3
"""gen_apb_seeds_manifest.py -- the AHB-to-APB bridge random-seed suite (Track A bus plan B2).

    python3.12 tools/gen/gen_apb_seeds_manifest.py --base 28600 --seeds 100 > tb/ahb2apb/run/env_seeds.toml

One row per seed: tb_apb_env +TEST=random (dividers in use) with +verilator+seed+<seed>; the seed is in
the row name, so logs/ahb2apb/history.tsv keeps every seed apart. Karthik's block bar asks
for 500 seeds accumulated from nightly runs with none failing in the last two weeks:
nightly_a regenerates this file with a new base each day (day of year x 100), as for
the DMA (gen_dma_seeds_manifest.py).
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("--base", type=int, required=True)
ap.add_argument("--seeds", type=int, default=100)
a = ap.parse_args()
print(f"""# AHB2APB random seeds (bus plan B2). GENERATED by tools/gen/gen_apb_seeds_manifest.py
# --base {a.base} --seeds {a.seeds} -- do not edit by hand. Run: make -f flow/mk/track_a_run.mk apb_seeds
[suite]
block = "ahb2apb"
name  = "env_seeds"
kind  = "sim"
xfail = "tb/ahb2apb/run/xfail.tsv"

[defaults]
flist   = "tb/ahb2apb/env/filelist_apb_env.f"
top     = "tb_apb_env"
marker  = '^RESULT: PASSED'
timeout = 1800""")
for s in range(a.base, a.base + a.seeds):
    print(f'\n[[test]]\nname     = "env_random_s{s}"\nplusargs = ["+TEST=random", "+verilator+seed+{s}"]\ndefines  = ["APB_ENV_DIV=24\'hE4E4E4"]')
