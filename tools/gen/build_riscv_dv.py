#!/usr/bin/env python3
"""build_riscv_dv.py -- riscv-dv random programs for the open flow (plan 5.5).

    python3 tools/gen/build_riscv_dv.py [--seeds 1-5] [--tests "arith loop"] [--jobs 16]

For every test of tb/core/riscv_dv/testlist (shared with the xrun flow,
`make riscv_dv`) and every seed: generate with riscv-dv pygen
(tools/gen/garuda_dv_gen.py, GARUDA target), assemble with the open toolchain
and tb/core/riscv_dv/link.ld, convert to hex, read `tohost`, and write
tb/core/run/riscv_dv.toml: every program on tb_boot with the Spike
co-simulation (one comparison per retired instruction), plus AHB checker and
the end marker. Generated files go to logs/core/raw/riscv_dv_build/.
Run: make -f flow/mk/track_a_run.mk core_riscv_dv [DV_SEEDS=1-5]
"""
import argparse, json, os, signal, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
T = os.environ.get("GARUDA_TOOLS", os.path.expanduser("~/tools"))
CC = os.path.join(os.environ.get("RISCV_BIN", f"{T}/riscv/bin"), os.environ.get("RISCV_PREFIX", "riscv-none-elf-"))
DV = os.environ.get("RISCV_DV", f"{T}/src/riscv-dv")
PY = os.environ.get("DV_PYTHON", f"{T}/venv-a/bin/python")
OUT = f"{R}/logs/core/raw/riscv_dv_build"
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def seeds(spec):
    s = []
    for part in spec.split(","):
        a, _, b = part.partition("-")
        s += list(range(int(a), int(b or a) + 1))
    return s


def build(name, seed):
    t = f"{name}_s{seed}"
    if a.keep and os.path.exists(f"{OUT}/{t}.hex"):      # already built from this list
        syms = dict((l.split()[2], l.split()[0]) for l in
                    subprocess.run([CC + "nm", f"{OUT}/{t}.elf"], capture_output=True, text=True).stdout.splitlines()
                    if len(l.split()) == 3)
        return t, syms.get("tohost"), None
    for ext in (".S", ".elf", ".bin", ".hex"):          # never reuse a stale program
        if os.path.exists(f"{OUT}/{t}{ext}"):
            os.remove(f"{OUT}/{t}{ext}")
    log = open(f"{OUT}/{t}.build.log", "w")
    # a constraint failure inside pygen's worker pool can hang it: bounded, and on
    # timeout the whole process group (wrapper, pygen, its pool) is killed
    g = subprocess.Popen([PY, f"{R}/tools/gen/garuda_dv_gen.py", "--test", name, "--seed", str(seed), "--out", OUT],
                         stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
    try:
        g.wait(timeout=900)
    except subprocess.TimeoutExpired:
        os.killpg(g.pid, signal.SIGKILL)
        g.wait()
        return t, None, "generator timed out (900 s)"
    src = f"{OUT}/{t}.S"
    if g.returncode or not os.path.exists(src):
        return t, None, "generator failed"
    elf, bin_, hexf = f"{OUT}/{t}.elf", f"{OUT}/{t}.bin", f"{OUT}/{t}.hex"
    c = subprocess.run([CC + "gcc", "-march=rv32i_zmmul_zicsr_zifencei", "-mabi=ilp32", "-mno-relax", "-fno-pic",
                        "-static", "-nostdlib", "-nostartfiles", "-Wa,--no-warn", f"-I{DV}/user_extension",
                        "-T", f"{R}/tb/core/riscv_dv/link.ld", "-no-pie", "-Wl,--no-warn-rwx-segments",
                        "-Wl,--build-id=none", src, "-o", elf], stdout=log, stderr=subprocess.STDOUT)
    if c.returncode:
        return t, None, "did not assemble/link"
    subprocess.run([CC + "objcopy", "-O", "binary", elf, bin_], check=True)
    subprocess.run([sys.executable, f"{R}/tools/elf2hex.py", bin_, hexf], check=True, capture_output=True)
    syms = dict((l.split()[2], l.split()[0]) for l in
                subprocess.run([CC + "nm", elf], capture_output=True, text=True).stdout.splitlines()
                if len(l.split()) == 3)
    return t, syms.get("tohost"), None


ap = argparse.ArgumentParser()
ap.add_argument("--seeds", default="1-5")
ap.add_argument("--tests", default="")
ap.add_argument("--jobs", type=int, default=16)
ap.add_argument("--maxcyc", type=int, default=2000000)
ap.add_argument("--keep", action="store_true", help="reuse programs already built")
a = ap.parse_args()
os.makedirs(OUT, exist_ok=True)
from garuda_dv_gen_list import load_testlist  # noqa: E402
names = [n for n in load_testlist() if not a.tests or n in a.tests.split()]
jobs = [(n, s) for n in names for s in seeds(a.seeds)]
with ThreadPoolExecutor(a.jobs) as ex:
    res = list(ex.map(lambda j: build(*j), jobs))
q = json.dumps
out = [f'''# Plan 5.5: riscv-dv random programs (pygen, GARUDA target) on tb_boot in step
# with Spike (tools/cosim/garuda_cosim.cc). Tests: tb/core/riscv_dv/testlist.
# GENERATED by tools/gen/build_riscv_dv.py --seeds {a.seeds} -- do not edit by hand.
# Run: make -f flow/mk/track_a_run.mk core_riscv_dv
[suite]
block = "core"
name  = "riscv_dv"
kind  = "prog"
xfail = "tb/core/run/xfail.tsv"

[bench]
flist = "tb/soc/filelist_boot_cosim.f"
top   = "tb_boot"
vl_flags = ["-CFLAGS", "-I$GARUDA_TOOLS/spike/include", "-LDFLAGS", "-L$GARUDA_TOOLS/spike/lib -lriscv -Wl,-rpath,$GARUDA_TOOLS/spike/lib"]

[defaults]
marker   = 'TOHOST=1 -> PASSED'
timeout  = 900
require  = ['AHB-PROTOCOL: iport=0 dport=0', 'COSIM: .* 0 mismatches']
''']
bad = 0
for t, tohost, err in res:
    if err:
        bad += 1
        print(f"  {t}: {err} (see {os.path.relpath(OUT, R)}/{t}.build.log)")
        continue
    out.append(f"[[test]]\nname = {q(t)}\nhex  = {q(os.path.relpath(OUT, R) + '/' + t + '.hex')}\n"
               f"plusargs = {q(['+MAXCYC=%d' % a.maxcyc, '+QUIET', '+TOHOST=' + tohost])}\n")
open(f"{R}/tb/core/run/riscv_dv.toml", "w").write("\n".join(out))
print(f"wrote tb/core/run/riscv_dv.toml: {len(res) - bad} programs ({len(names)} tests x {len(seeds(a.seeds))} seeds), {bad} not built")
sys.exit(1 if bad else 0)
