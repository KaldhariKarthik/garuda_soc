#!/usr/bin/env python3
"""port_dsu_benches.py -- plan D1: bring the dsu-verification branch's sub-block
benches onto the real DSU RTL.

    python3 tools/gen/port_dsu_benches.py     (needs `git fetch`; reads origin/dsu-verification)

Every bench on that branch carries a pasted (and possibly stale) copy of the
module it tests, so it verifies the copy, not the design. This takes each
bench from the branch, removes every top-level module whose name is a DSU RTL
module, keeps the bench (classes, SVA, tb_top) unchanged, adds a header
crediting the source commit and author, and writes tb/dsu/units/<bench>.sv and
the manifest tb/dsu/run/units.toml (each bench compiled with rtl/dsu/filelist.f,
i.e. against the real RTL). Benches that then fail are triaged, not edited
here: a port change or an RTL finding.
"""
import json, os, re, subprocess

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BR = "origin/dsu-verification"
git = lambda *a: subprocess.run(["git", "-C", R, *a], capture_output=True, text=True, check=True).stdout
dsu_mods = set()
for f in os.listdir(f"{R}/rtl/dsu"):
    if f.endswith(".v"):
        dsu_mods |= set(re.findall(r"^\s*module\s+(\w+)", open(f"{R}/rtl/dsu/{f}").read(), re.M))
files = [f for f in git("diff", "--name-only", f"origin/main...{BR}").split()
         if re.match(r"tb/dsu/tb_dsu_\w+\.sv$", f)]
q = json.dumps
rows = ['''# Plan D1: the dsu-verification sub-block benches on the REAL DSU RTL.
# GENERATED by tools/gen/port_dsu_benches.py -- do not edit by hand.
# Run: make -f flow/mk/track_a_run.mk dsu_units
[suite]
block = "dsu"
name  = "units"
kind  = "sim"
xfail = "tb/dsu/run/xfail.tsv"

[defaults]
top     = "tb_top"
marker  = 'RESULT: ALL CHECKS PASSED'
timeout = 300
cwd     = "root"
''']
for f in sorted(files):
    src = git("show", f"{BR}:{f}")
    sha, who, when = git("log", "-1", "--format=%h|%an|%ad", "--date=short", BR, "--", f).strip().split("|")
    removed = []

    def strip(m):
        if m.group(1) in dsu_mods:
            removed.append(m.group(1)); return ""
        return m.group(0)
    body = re.sub(r"^module\s+(\w+)\b.*?^endmodule\b[^\n]*\n", strip, src, flags=re.M | re.S)
    # TOOL-23: Verilator 5.052 aborts (internal fault) on a class covergroup that
    # samples through a virtual interface, and its get_coverage() is always 0
    # (TOOL-22). Under VERILATOR the covergroups are compiled out and their
    # coverage reads -1 ("not measured"); Xcelium compiles them unchanged.
    cgs = re.findall(r"\bcovergroup\s+(\w+)", body)
    for cg in cgs:
        body = re.sub(rf"(\bcovergroup\s+{cg}\b.*?\bendgroup\b[^\n]*)", r"`ifndef VERILATOR\n\1\n`endif", body, flags=re.S)
        body = re.sub(rf"(?<![\w.]){cg}\s*=\s*new\s*\(\s*\)\s*;", f"`GARUDA_CG_NEW({cg})", body)
        body = re.sub(rf"((?:\w+\.)*{cg})\.sample\s*\(\s*\)\s*;", r"`GARUDA_CG_SAMPLE(\1)", body)
        body = re.sub(rf"(?<![\w.])((?:\w+\.)*{cg})\.get(?:_inst)?_coverage\(\)", r"`GARUDA_CG_COV(\1)", body)
    if cgs:
        body = ("`ifdef VERILATOR\n  `define GARUDA_CG_NEW(cg)\n  `define GARUDA_CG_SAMPLE(cg)\n"
                "  `define GARUDA_CG_COV(cg) (-1.0)\n`else\n  `define GARUDA_CG_NEW(cg) cg = new();\n"
                "  `define GARUDA_CG_SAMPLE(cg) cg.sample();\n  `define GARUDA_CG_COV(cg) cg.get_coverage()\n`endif\n"
                + body)
    name = os.path.basename(f)[:-3]
    hdr = (f"// PORTED by tools/gen/port_dsu_benches.py from {BR} {sha} ({f}), author {who}, {when}.\n"
           f"// Pasted copies of the design removed ({', '.join(removed) or 'none'}): this bench now\n"
           f"// compiles against rtl/dsu (the real RTL). Covergroups {', '.join(cgs) or '-'} compiled out\n"
           f"// under Verilator only (TOOL-23); otherwise unchanged.\n")
    open(f"{R}/tb/dsu/units/{name}.sv", "w").write(hdr + body)
    fl = f"tb/dsu/units/{name}.f"
    # the whole DSU filelist, properties included: dsu_props_a.sv binds into every
    # mac_unit a bench instantiates (and dsu_top, unused here)
    open(f"{R}/{fl}", "w").write(f"-f rtl/dsu/filelist.f\ntb/dsu/units/{name}.sv\n")
    rows.append(f"[[test]]\nname  = {q(name)}\nflist = {q(fl)}\n")
open(f"{R}/tb/dsu/run/units.toml", "w").write("\n".join(rows))
print(f"ported {len(files)} benches to tb/dsu/units/")
