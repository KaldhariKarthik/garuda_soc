#!/usr/bin/env python3
"""gen_cosim_manifest.py -- write tb/core/run/cosim.toml (plan 5.2 / 5.3).

Every program of the isa, sanity, extra, directed and covtests suites, each with
its own plusargs, on tb_boot built with the Spike co-simulation
(tb/soc/filelist_boot_cosim.f). Regenerate when those manifests change:
    python3 tools/gen/gen_cosim_manifest.py
"""
import json, os, tomllib
R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
q = json.dumps
out = ['''# Plan 5.2 / 5.3: the core in step with Spike (tools/cosim/garuda_cosim.cc),
# one comparison per retired instruction, interrupts applied from the spec.
# GENERATED by tools/gen/gen_cosim_manifest.py -- do not edit by hand.
# Run: make -f flow/mk/track_a_run.mk core_cosim
[suite]
block = "core"
name  = "cosim"
kind  = "prog"
xfail = "tb/core/run/xfail.tsv"

[bench]
flist = "tb/soc/filelist_boot_cosim.f"
top   = "tb_boot"
vl_flags = ["-CFLAGS", "-I$GARUDA_TOOLS/spike/include", "-LDFLAGS", "-L$GARUDA_TOOLS/spike/lib -lriscv -Wl,-rpath,$GARUDA_TOOLS/spike/lib"]

[defaults]
marker   = 'TOHOST=1 -> PASSED'
timeout  = 900
require  = ['AHB-PROTOCOL: iport=0 dport=0', 'COSIM: .* 0 mismatches']
''']
# a known expected failure of its own suite (xfail.tsv, e.g. a test written for an
# open bug) is not carried into the co-simulation set
xfails = {tuple(l.split("\t")[:2]) for l in open(f"{R}/tb/core/run/xfail.tsv") if not l.startswith("#")}
for m in ["isa", "sanity", "extra", "directed", "covtests"]:
    d = tomllib.load(open(f"{R}/tb/core/run/{m}.toml", "rb"))
    dpl = d.get("defaults", {}).get("plusargs", [])
    for pg in d.get("programs", []):
        out.append(f"[[programs]]\nglob = {q(pg['glob'])}\nplusargs = {q(pg.get('plusargs', dpl))}\n")
    for t in d.get("test", []):
        if not t.get("hex") or (m, t["name"]) in xfails:
            continue
        out.append(f"[[test]]\nname = {q('cs_' + t['name'])}\nhex  = {q(t['hex'])}\n"
                   f"plusargs = {q(t.get('plusargs', dpl))}\n")
open(f"{R}/tb/core/run/cosim.toml", "w").write("\n".join(out))
print("wrote tb/core/run/cosim.toml")
