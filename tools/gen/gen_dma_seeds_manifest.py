#!/usr/bin/env python3
"""gen_dma_seeds_manifest.py -- the DMA random-seed suite (Track A, DMA plan D5).

    python3.12 tools/gen/gen_dma_seeds_manifest.py --base 28500 --seeds 100 > tb/dma/run/env_seeds.toml

One row per seed: tb_dma_env +TEST=rand with +verilator+seed+<seed>; the seed is in
the row name, so logs/dma/history.tsv keeps every seed apart. Karthik's block bar
asks for 500 seeds accumulated from nightly runs with none failing in the last two
weeks: nightly_a regenerates this file with a new base each day (day of year x 100),
so five nights give 500 distinct seeds.
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("--base", type=int, required=True)
ap.add_argument("--seeds", type=int, default=100)
ap.add_argument("--iter", type=int, default=20)
a = ap.parse_args()
print(f"""# DMA random seeds (DMA plan D5). GENERATED by tools/gen/gen_dma_seeds_manifest.py
# --base {a.base} --seeds {a.seeds} -- do not edit by hand. Run: make -f flow/mk/track_a_run.mk dma_seeds
[suite]
block = "dma"
name  = "env_seeds"
kind  = "sim"
xfail = "tb/dma/run/xfail.tsv"

[defaults]
flist   = "tb/dma/env/filelist_dma_env.f"
top     = "tb_dma_env"
marker  = '^RESULT: PASSED'
timeout = 1800""")
for s in range(a.base, a.base + a.seeds):
    print(f'\n[[test]]\nname     = "env_rand_s{s}"\nplusargs = ["+TEST=rand", "+ITER={a.iter}", "+verilator+seed+{s}"]')
