#!/usr/bin/env python3
"""gen_dsu_mutants.py -- plan 5.11 / D7: the DSU planted-defect run.

    python3 tools/gen/gen_dsu_mutants.py      (writes tb/dsu/mut/*.v + tb/dsu/run/dsu_mut.toml)

Each mutant is one realistic defect applied to a copy of one DSU RTL file (the
pattern must match exactly once, so a mutant follows the RTL as it changes).
It is run at the level whose checker kills it, and must FAIL there for the
named reason (KILLED-BY-CHECK, plan "Mutation"):
  block  tb_dsu_top: the scoreboard against the independent model ('mismatches')
  core   tb_boot running t_cov_dsu (ArchDSU-checked program, fail code) with the
         DSU properties bound -- for the timing / flag defects the block bench
         cannot see: it replays one instruction per vector with idle cycles,
         so it never reads an accumulator right behind its MAC and never
         carries the overflow flag across instructions (analysis in
         Docs/bugs/dsu.md TB-42)
Every mutant is also a formal negative control in tb/dsu/formal/dsu.toml
(dsu_mut_<name>) when a proven property covers it. The rows are PLANTED in
tb/dsu/run/xfail.tsv; a mutant that passes is an XPASS error and needs an
analysis or a new check.
Run: make -f flow/mk/track_a.mk dsu_mut
"""
import json, os, re

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VEC = ["+STIM=logs/dsu/raw/vec/dsu_stim.mem", "+EXP=logs/dsu/raw/vec/dsu_expected.mem"]
CLAMP = ["+STIM=logs/dsu/raw/vec_clamp/dsu_stim.mem", "+EXP=logs/dsu/raw/vec_clamp/dsu_expected.mem"]
SB = r"mismatches *: *[1-9]"
CORE = "core"
FORMAL = "formal"   # killed only by a proven property: a negative-control task in tb/dsu/formal/dsu.toml
PROG = r"TOHOST=.*FAILED|\[SVA-FAIL\] DSU"
# name, file, pattern, replacement, stimulus (CORE = tb_boot + t_cov_dsu), expected reason, what it models
MUTANTS = [
    ("shift_logical", "barrel_shifter.v", "acc_signed >>> shift_amt", "cluster_out >> shift_amt", VEC, SB,
     "MACSHIFT right shift loses the sign (the DSU shift erratum reverted)"),
    ("rdhi_zext", "readback_mux.v", "{{16{cluster_out[47]}}, cluster_out[47:32]}", "{16'b0, cluster_out[47:32]}",
     VEC, SB, "MACRD_HI zero-extends instead of sign-extending"),
    ("dot_hi_is_lo", "operand_router.v", "dot_active ? rs1[31:16] : 16'b0", "dot_active ? rs1[15:0] : 16'b0",
     VEC, SB, "MACDOT multiplies the low halfword twice"),
    ("no_interlock", "dsu_stall.v", "assign dsu_busy = stall_now;", "assign dsu_busy = 1'b0;", CORE,
     PROG, "the read-after-MAC interlock never fires"),
    ("no_fold", "mac_unit.v", "else             pending <= prod_en;", "else             pending <= 1'b0;", VEC,
     SB, "the stage-2 fold of an accumulate never happens"),
    ("sat_no_ovf", "saturation_unit.v", "assign sat_overflow     = sat_op & ~in_range;",
     "assign sat_overflow     = 1'b0;", VEC, SB, "MACSAT clamps but never sets the overflow flag"),
    ("ovf_not_sticky", "overflow_flag.v", "else if (any_ovf)            dsu_overflow <= 1'b1;",
     "else                         dsu_overflow <= any_ovf;", CORE, PROG,
     "the overflow flag is not sticky"),
    ("ovf_clear_drops_set", "overflow_flag.v", "else if (csr_clear_overflow) dsu_overflow <= any_ovf;",
     "else if (csr_clear_overflow) dsu_overflow <= 1'b0;", FORMAL, "a_ovf_set_beats_clear",
     "an overflow in the clear cycle is lost"),
]
q = json.dumps
rows = ['''# Plan 5.11 / D7: DSU planted defects. GENERATED by tools/gen/gen_dsu_mutants.py
# -- do not edit by hand. Every row must FAIL for its reason (PLANTED in
# tb/dsu/run/xfail.tsv). Run: make -f flow/mk/track_a.mk dsu_mut
[suite]
block = "dsu"
name  = "dsu_mut"
kind  = "sim"
xfail = "tb/dsu/run/xfail.tsv"

[defaults]
flist   = "tb/dsu/filelist_dsu_top.f"
top     = "tb_dsu_top"
marker  = 'RESULT *: PASSED'
timeout = 1200
cwd     = "root"
''']
xf = []
for name, f, pat, rep, stim, reason, what in MUTANTS:
    src = open(f"{R}/rtl/dsu/{f}").read()
    n = src.count(pat)
    if n != 1:
        raise SystemExit(f"{name}: pattern found {n} times in rtl/dsu/{f}")
    out = f"tb/dsu/mut/{f[:-2]}_mut_{name}.v"
    open(f"{R}/{out}", "w").write(f"// MUTANT dsu_mut/{name} (GENERATED by tools/gen/gen_dsu_mutants.py): {what}\n"
                                   + src.replace(pat, rep))
    if stim == FORMAL:
        print(f"  {name}: formal only (fv_dsu dsu_mut_{name} must fail {reason})")
        continue
    if stim == CORE:
        bench = ('flist   = "tb/soc/filelist_boot.f"\ntop     = "tb_boot"\nmarker  = \'TOHOST=1 -> PASSED\'\n'
                 f"plusargs = {q(['+HEX=sw/build/t_cov_dsu.hex', '+MAXCYC=8000000', '+QUIET'])}\n")
    else:
        bench = f"plusargs = {q(stim)}\n"
    rows.append(f"# {what}\n[[test]]\nname = {q('mut_' + name)}\n{bench}"
                f"replace = {{ {q('rtl/dsu/' + f)} = {q(out)} }}\nfail_reason = {q(reason)}\n")
    xf.append(f"dsu_mut\tmut_{name}\tFAIL\tPLANTED\tDSU mutant: {what}")
open(f"{R}/tb/dsu/run/dsu_mut.toml", "w").write("\n".join(rows))
x = f"{R}/tb/dsu/run/xfail.tsv"
old = [l for l in open(x).read().splitlines() if not l.startswith("dsu_mut\t")] if os.path.exists(x) else []
open(x, "w").write("\n".join(old + xf) + "\n")
print(f"wrote {len(MUTANTS)} mutants to tb/dsu/mut/ and tb/dsu/run/dsu_mut.toml")
