#!/usr/bin/env python3
"""Generate tb/common/garuda_map_pkg.sv from Design_Docs/garuda_system.yaml.

Track A bus plan B0: the ONE expected-map source for every bus/DMA model and
test (address regions and the APB aperture, the 12 APB windows, AHB master
priorities and reachability, DMA channel assignment and priority order, CLIC
IDs). Nothing in a testbench restates these values by hand; it imports
garuda_map_pkg. The package is verification-only (not synthesised).

    python3 tools/gen/gen_map_pkg.py           # write the package
    python3 tools/gen/gen_map_pkg.py --check   # exit 1 if the file is stale

tb/common/tb_map_pkg.sv cross-checks the package against the RTL header
rtl/include/garuda_map.vh (written by tools/garuda_gen.py from the same YAML),
so a drift between the two generators is caught in simulation.
"""
import argparse
import os
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
YAML = os.path.join(ROOT, "Design_Docs", "garuda_system.yaml")
OUT = os.path.join(ROOT, "tb", "common", "garuda_map_pkg.sv")


def id_range(v):
    if isinstance(v, int):
        return [v]
    a, b = str(v).split("..")
    return list(range(int(a), int(b) + 1))


def render(sd):
    regions = sd["address_map"]["regions"]
    apb = sd["apb"]
    wins = sorted(apb["windows"], key=lambda w: w["index"])
    masters = sorted(sd["ahb"]["masters"], key=lambda m: m["id"])
    reach = sd["ahb"]["master_reachability"]
    dma = sd["dma"]
    clic = sd["clic"]["map"]

    L = []
    w = L.append
    w("// " + "=" * 77)
    w("// garuda_map_pkg.sv -- GENERATED by tools/gen/gen_map_pkg.py from")
    w("// Design_Docs/garuda_system.yaml (%s rev %s). DO NOT EDIT: rerun the script."
      % (sd["meta"]["doc_id"], sd["meta"]["revision"]))
    w("//")
    w("// Track A bus plan B0: the single expected-map source for bus and DMA models,")
    w("// scoreboards and tests. Verification only, never synthesised.")
    w("// Checked against rtl/include/garuda_map.vh by tb/common/tb_map_pkg.sv.")
    w("// " + "=" * 77)
    w("package garuda_map_pkg;")
    w("")
    w("  // ---- address regions (decode on HADDR[31:28]) " + "-" * 30)
    w("  typedef enum int {R_ISRAM = 0, R_BOOTROM = 1, R_DSRAM = 2, R_APB = 3, R_NONE = 4} region_e;")
    names = {"ISRAM": "R_ISRAM", "BOOTROM": "R_BOOTROM", "DSRAM": "R_DSRAM", "APB": "R_APB"}
    for r in regions:
        w("  localparam logic [31:0] %s_BASE = 32'h%08X;  localparam int unsigned %s_BYTES = %d;  // %s"
          % (r["name"], r["base"], r["name"], r["size_kib"] * 1024, r["access"]))
    w("")
    w("  // Region of an address: the nibble decode AND the in-region size. An address")
    w("  // inside a decoded nibble but past the region's size is R_NONE here (that is the")
    w("  // specified behaviour; whether the RTL faults on it is per-slave, e.g. APB-2).")
    w("  function automatic region_e region_of(input logic [31:0] a);")
    for r in regions:
        w("    if (a[31:28] == 4'h%X && (a - %s_BASE) < %s_BYTES) return %s;"
          % (r["base"] >> 28, r["name"], r["name"], names[r["name"]]))
    w("    return R_NONE;")
    w("  endfunction")
    w("  function automatic bit region_nibble_decoded(input logic [3:0] n);   // the AHB decoder's view")
    w("    return " + " || ".join("n == 4'h%X" % (r["base"] >> 28) for r in regions) + ";")
    w("  endfunction")
    w("  function automatic bit region_writable(input region_e r);")
    wr = [names[r["name"]] for r in regions if "w" in r["access"]]
    w("    return " + " || ".join("r == %s" % x for x in wr) + ";")
    w("  endfunction")
    w("")
    w("  // ---- APB windows " + "-" * 58)
    w("  localparam int unsigned APB_WINDOWS      = %d;" % len(wins))
    w("  localparam int unsigned APB_WINDOW_BYTES = %d;" % (apb["window_size_kib"] * 1024))
    w("  localparam int unsigned APB_TIMEOUT_PCLK = %d;" % apb["timeout_cycles"])
    w("  localparam bit          APB_WORD_ONLY    = 1'b%d;" % (1 if apb["access"] == "word_only" else 0))
    mask = 0
    for x in wins:
        mask |= 1 << x["index"]
        assert x["base"] == 0x40000000 + 0x1000 * x["index"], x
    w("  localparam logic [15:0] APB_WINDOW_MASK_ALL = 16'h%04X;" % mask)
    w("  localparam string APB_WIN_NAME [%d] = '{%s};"
      % (len(wins), ", ".join('"%s"' % x["name"] for x in wins)))
    for x in wins:
        w("  localparam int unsigned WIN_%s = %d;" % (x["name"].upper(), x["index"]))
    w("  // Window an access selects per the map: -1 = no window (outside the aperture,")
    w("  // or a window absent from `mask`). Sub-word legality is separate (APB_WORD_ONLY).")
    w("  function automatic int apb_window_of(input logic [31:0] a, input logic [15:0] mask = APB_WINDOW_MASK_ALL);")
    w("    if (region_of(a) != R_APB) return -1;")
    w("    if (!mask[a[15:12]]) return -1;")
    w("    return int'(a[15:12]);")
    w("  endfunction")
    w("")
    w("  // ---- AHB masters (fixed priority, higher number wins) " + "-" * 22)
    w("  localparam int unsigned AHB_MASTERS = %d;" % len(masters))
    for m in masters:
        w("  localparam int unsigned M_%s = %d;  // priority %d, bursts %s, %s"
          % (m["name"].upper(), m["id"], m["priority"], "/".join(m["bursts"]), "/".join(m["access"])))
    w("  localparam int unsigned AHB_PRIORITY [%d] = '{%s};"
      % (len(masters), ", ".join(str(m["priority"]) for m in masters)))
    w("  localparam string AHB_MASTER_NAME [%d] = '{%s};"
      % (len(masters), ", ".join('"%s"' % m["name"] for m in masters)))
    w("  // Winner among a request set at a beat boundary (-1 if none).")
    w("  function automatic int ahb_winner(input logic [%d:0] req);" % (len(masters) - 1))
    w("    int best = -1;")
    w("    for (int m = 0; m < %d; m++) if (req[m] && (best < 0 || AHB_PRIORITY[m] > AHB_PRIORITY[best])) best = m;" % len(masters))
    w("    return best;")
    w("  endfunction")
    w("  // Reachability per garuda_system.yaml ahb.master_reachability (normative; see DMA-17).")
    w("  function automatic bit master_reaches(input int m, input region_e r);")
    w("    case (m)")
    rmap = {"isram": "R_ISRAM", "bootrom": "R_BOOTROM", "dsram": "R_DSRAM", "apb": "R_APB"}
    for mm in masters:
        lst = reach[mm["name"]]
        w("      %d: return %s;  // %s" % (mm["id"], " || ".join("r == %s" % rmap[x] for x in lst), mm["name"]))
    w("      default: return 1'b0;")
    w("    endcase")
    w("  endfunction")
    w("")
    w("  // ---- DMA " + "-" * 66)
    asg = sorted(dma["assignment"], key=lambda a: a["ch"])
    w("  localparam int unsigned DMA_CHANNELS = %d;" % dma["channels"])
    w("  localparam int unsigned DMA_PRIO [%d] = '{%s};  // higher wins"
      % (len(asg), ", ".join(str(a["priority"]) for a in asg)))
    order = [a["ch"] for a in sorted(asg, key=lambda a: -a["priority"])]
    w("  localparam int unsigned DMA_PRIO_ORDER [%d] = '{%s};  // channels, highest first"
      % (len(order), ", ".join(map(str, order))))
    w("  localparam string DMA_PERIPH [%d] = '{%s};"
      % (len(asg), ", ".join('"%s"' % a["peripheral"] for a in asg)))
    w("  // APB window of each channel's peripheral (its data register lives there).")
    widx = {x["name"]: x["index"] for x in wins}
    w("  localparam int unsigned DMA_PERIPH_WIN [%d] = '{%s};"
      % (len(asg), ", ".join(str(widx[a["peripheral"]]) for a in asg)))
    w("  function automatic int dma_winner(input logic [%d:0] req);" % (len(asg) - 1))
    w("    int best = -1;")
    w("    for (int c = 0; c < %d; c++) if (req[c] && (best < 0 || DMA_PRIO[c] > DMA_PRIO[best])) best = c;" % len(asg))
    w("    return best;")
    w("  endfunction")
    w("")
    w("  // ---- CLIC IDs " + "-" * 61)
    ids = {}
    for e in clic:
        for i in id_range(e["id"]):
            ids[i] = e["source"]
    comp = [i for i in sorted(ids) if ids[i] == "dma_complete_ch0_5"]
    err = [i for i in sorted(ids) if ids[i] == "dma_error_ch0_5"]
    assert len(comp) == dma["channels"] and len(err) == dma["channels"]
    w("  localparam int unsigned CLIC_ID_DMA_COMPLETE [%d] = '{%s};" % (len(comp), ", ".join(map(str, comp))))
    w("  localparam int unsigned CLIC_ID_DMA_ERROR    [%d] = '{%s};" % (len(err), ", ".join(map(str, err))))
    resv = [i for i in sorted(ids) if ids[i].startswith("reserved")]
    w("  localparam int unsigned CLIC_ID_RESERVED [%d] = '{%s};  // never driven by a source"
      % (len(resv), ", ".join(map(str, resv))))
    for i in sorted(ids):
        s = ids[i]
        if s.startswith("reserved") or s.startswith("dma_"):
            continue
        w("  localparam int unsigned CLIC_ID_%s = %d;" % (s.upper(), i))
    w("")
    w("endpackage")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the package is stale")
    a = ap.parse_args()
    with open(YAML) as f:
        sd = yaml.safe_load(f)
    text = render(sd)
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("gen_map_pkg: %s is STALE; rerun tools/gen/gen_map_pkg.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("gen_map_pkg: %s up to date" % os.path.relpath(OUT, ROOT))
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("gen_map_pkg: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
