#!/usr/bin/env python3
"""gen_stress_manifest.py -- plan 5.10: reset / halt / WFI / interrupt / fault
storms over many seeds.

    python3 tools/gen/gen_stress_manifest.py [--seeds 1000]

Writes two GENERATED manifests (seed i is row i; every choice is drawn from
random.Random(i), so a row reproduces from its seed alone):
  tb/core/run/stress.toml       70 %: every self-checking directed / coverage
      program (WFI, nested and preempting CLIC interrupts, bus errors under
      MRET / WFI, fetch faults, warm reset at a random cycle, DSU, misaligned
      targets) on tb_boot WITH the Spike co-simulation, under random I/D wait
      profiles (fixed or random per beat) and a random bench seed
  tb/core/run/stress_halt.toml  30 %: halt-by-reset (ADR-0012) storms on
      tb_core_halt, 60 halts per run at random moments, random data waits
A row passes only with the program's own PASS marker, a clean AHB-Lite checker
and (stress.toml) zero co-simulation mismatches.
Run: make -f flow/mk/track_a.mk core_stress
"""
import argparse, json, os, random, re, tomllib

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
q = json.dumps
ap = argparse.ArgumentParser()
ap.add_argument("--seeds", type=int, default=1000)
a = ap.parse_args()

# one entry per program: the base plusargs of its first row (wait / reset
# plusargs are redrawn per seed)
# a program that is an expected failure (xfail.tsv, e.g. a test written for an
# open bug) is not stress material
xfails = {tuple(l.split("\t")[:2]) for l in open(f"{R}/tb/core/run/xfail.tsv") if not l.startswith("#")}
progs = {}
for m in ["directed", "covtests"]:
    d = tomllib.load(open(f"{R}/tb/core/run/{m}.toml", "rb"))
    dpl = d.get("defaults", {}).get("plusargs", [])
    for t in d.get("test", []):
        h = t.get("hex")
        if not h or h in progs or (m, t["name"]) in xfails:
            continue
        base = [p for p in t.get("plusargs", dpl)
                if not re.match(r"\+(IWAIT|DWAIT|IRAND|DRAND|SEED|RERESET_AT)=", p)]
        progs[h] = (os.path.basename(h)[:-4], base, any(p.startswith("+RERESET_AT=") for p in t.get("plusargs", [])))
plist = sorted(progs.values())
# programs whose own checks are timing claims valid only without bus waits
# (t_core_ctl check 3, see its source; t_core_ctl_arch is its any-wait twin):
# their rows keep zero waits (the draw is still made, so every other row stays
# the same program and profile)
ZERO_WAIT = {"t_core_ctl"}

HDR = '''# Plan 5.10: stress over seeds. GENERATED by tools/gen/gen_stress_manifest.py
# --seeds {n} -- do not edit by hand. Row = seed; all choices from Random(seed).
# Run: make -f flow/mk/track_a.mk core_stress
'''
boot = [HDR.format(n=a.seeds) + '''[suite]
block = "core"
name  = "stress"
kind  = "prog"
xfail = "tb/core/run/xfail.tsv"

[bench]
flist = "tb/soc/filelist_boot_cosim.f"
top   = "tb_boot"
vl_flags = ["-CFLAGS", "-I$GARUDA_TOOLS/spike/include", "-LDFLAGS", "-L$GARUDA_TOOLS/spike/lib -lriscv -Wl,-rpath,$GARUDA_TOOLS/spike/lib"]

[defaults]
marker   = 'TOHOST=1 -> PASSED'
timeout  = 900
require  = ['AHB-PROTOCOL: iport=0 dport=0', 'COSIM: .* 0 mismatches']
''']
halt = [HDR.format(n=a.seeds) + '''[suite]
block = "core"
name  = "stress_halt"
kind  = "sim"
xfail = "tb/core/run/xfail.tsv"

[defaults]
flist   = "tb/core/filelist_core_halt.f"
top     = "tb_core_halt"
marker  = 'ALL CHECKS PASSED'
timeout = 600
cwd     = "root"
require = ['AHB-PROTOCOL: iport=0 dport=0']
''']
nb = nh = 0
for s in range(1, a.seeds + 1):
    rng = random.Random(s)
    if rng.random() < 0.30:
        nh += 1
        dw = rng.randint(1, 8)
        # tb_core_halt fails a run in which no halt lands on a waited store
        # (non-vacuity); short waits make that window small, so more halts
        nh_ = 60 if dw >= 3 else 150
        halt.append(f"[[test]]\nname = {q('halt_s%d' % s)}\nplusargs = "
                    f"{q(['+HEX=sw/build/t_mem.hex', '+NHALT=%d' % nh_, '+DWAIT=%d' % dw, '+SEED=%d' % s])}\n")
        continue
    nb += 1
    name, base, rereset = plist[rng.randrange(len(plist))]
    iw, dw = rng.choice([0, 0, 1, 2, 3, 5, 8]), rng.choice([0, 0, 1, 2, 3, 5, 8])
    if name in ZERO_WAIT:
        iw = dw = 0
    pl = []
    for p in base:
        m = re.match(r"\+MAXCYC=(\d+)", p)
        pl.append(f"+MAXCYC={int(m.group(1)) * (2 + max(iw, dw))}" if m else p)
    ir, dr = rng.randint(0, 1), rng.randint(0, 1)
    if name in ZERO_WAIT:
        ir = dr = 0
    pl += [f"+IWAIT={iw}", f"+DWAIT={dw}", f"+IRAND={ir}", f"+DRAND={dr}", f"+SEED={s}"]
    if rereset:
        pl.append(f"+RERESET_AT={rng.randint(600, 3000)}")
    hexf = [h for h, v in progs.items() if v[0] == name][0]
    boot.append(f"[[test]]\nname = {q('%s_s%d' % (name, s))}\nhex  = {q(hexf)}\nplusargs = {q(pl)}\n")
open(f"{R}/tb/core/run/stress.toml", "w").write("\n".join(boot))
open(f"{R}/tb/core/run/stress_halt.toml", "w").write("\n".join(halt))
print(f"wrote tb/core/run/stress.toml ({nb} rows over {len(plist)} programs) and stress_halt.toml ({nh} rows)")
