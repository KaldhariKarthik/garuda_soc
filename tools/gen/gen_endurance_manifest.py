#!/usr/bin/env python3
"""gen_endurance_manifest.py -- plan 5.12 / E12: the 1e9-instruction endurance run.

    python3 tools/gen/gen_endurance_manifest.py [--target 1.05e9]

Writes tb/core/run/endurance.toml (GENERATED): long self-checking programs on
tb_boot with the Spike co-simulation, so every counted instruction is compared
with Spike (plan: "counts only co-simulation-checked instructions"):
  t_perf_mix  912,524 instructions: loads / stores / MUL / branches / calls
  t_cov_dsu   590,417 instructions: every DSU op, 48-bit accumulate overflows,
              dsu_ovf read-to-clear, all checked against ArchDSU as well
each row under its own random I/D wait profile and bench seed (row i draws
from random.Random(i)). No commit log on disk (no_commit; ~27 GB otherwise):
the co-simulation is the checker. The count and the workload diversity are
reported by tools/run/instret_report.py over this and the other co-simulation
suites (cosim, stress, riscv_dv). Not coverage closure (plan E12).
Run: make -f flow/mk/track_a.mk core_endurance instret_report
"""
import argparse, json, os, random

ap = argparse.ArgumentParser()
ap.add_argument("--target", type=float, default=1.05e9)
a = ap.parse_args()
R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PROGS = [("t_perf_mix", 912524, 0.86, 80000000), ("t_cov_dsu", 590417, 0.14, 40000000)]
q = json.dumps
out = [f'''# Plan 5.12: endurance, >= {a.target:.3g} co-simulation-checked instructions.
# GENERATED by tools/gen/gen_endurance_manifest.py -- do not edit by hand.
# Run: make -f flow/mk/track_a.mk core_endurance instret_report
[suite]
block = "core"
name  = "endurance"
kind  = "prog"
xfail = "tb/core/run/xfail.tsv"

[bench]
flist = "tb/soc/filelist_boot_cosim.f"
top   = "tb_boot"
vl_flags = ["-CFLAGS", "-I$GARUDA_TOOLS/spike/include", "-LDFLAGS", "-L$GARUDA_TOOLS/spike/lib -lriscv -Wl,-rpath,$GARUDA_TOOLS/spike/lib"]

[defaults]
marker    = 'TOHOST=1 -> PASSED'
timeout   = 1800
no_commit = true
require   = ['AHB-PROTOCOL: iport=0 dport=0', 'COSIM: .* 0 mismatches']
''']
total, i = 0, 0
while total < a.target:
    i += 1
    rng = random.Random(1_000_000 + i)
    name, n, _, maxcyc = PROGS[0] if rng.random() < PROGS[0][2] else PROGS[1]
    iw, dw = rng.choice([0, 0, 1, 2, 3, 5, 8]), rng.choice([0, 0, 1, 2, 3, 5, 8])
    pl = [f"+MAXCYC={maxcyc * (1 + max(iw, dw))}", "+QUIET", f"+IWAIT={iw}", f"+DWAIT={dw}",
          f"+IRAND={rng.randint(0, 1)}", f"+DRAND={rng.randint(0, 1)}", f"+SEED={i}"]
    out.append(f"[[test]]\nname = {q('%s_e%d' % (name, i))}\nhex  = {q('sw/build/%s.hex' % name)}\nplusargs = {q(pl)}\n")
    total += n
open(f"{R}/tb/core/run/endurance.toml", "w").write("\n".join(out))
print(f"wrote tb/core/run/endurance.toml: {i} rows, {total:,} instructions planned")
