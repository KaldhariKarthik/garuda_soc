#!/usr/bin/env python3
"""gen_ahb_seeds_manifest.py -- the AHB interconnect random-seed suite (Track A bus plan B1, A5).

    python3.12 tools/gen/gen_ahb_seeds_manifest.py --base 28600 --seeds 100 > tb/ahb/run/env_seeds.toml

One row per seed: tb_ahb_env +TEST=random with +verilator+seed+<seed>; the seed is in
the row name, so logs/ahb/history.tsv keeps every seed apart. Karthik's block bar asks
for 500 seeds accumulated from nightly runs with none failing in the last two weeks:
nightly_a regenerates this file with a new base each day (day of year x 100), as for
the DMA (gen_dma_seeds_manifest.py).
"""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("--base", type=int, required=True)
ap.add_argument("--seeds", type=int, default=100)
a = ap.parse_args()
print(f"""# AHB random seeds (bus plan B1 A5). GENERATED by tools/gen/gen_ahb_seeds_manifest.py
# --base {a.base} --seeds {a.seeds} -- do not edit by hand. Run: make -f flow/mk/track_a.mk ahb_seeds
[suite]
block = "ahb"
name  = "env_seeds"
kind  = "sim"
xfail = "tb/ahb/run/xfail.tsv"

[defaults]
flist   = "tb/ahb/env/filelist_ahb_env.f"
top     = "tb_ahb_env"
marker  = '^RESULT: PASSED'
timeout = 1800""")
for s in range(a.base, a.base + a.seeds):
    print(f'\n[[test]]\nname     = "env_random_s{s}"\nplusargs = ["+TEST=random", "+verilator+seed+{s}"]')
