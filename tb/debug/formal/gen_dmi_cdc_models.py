#!/usr/bin/env python3
"""gen_dmi_cdc_models.py -- cut the formal-only copies of rtl/debug/dmi_cdc.v from the CURRENT RTL:
the metastability-injection model (D1, tb/debug/formal/dmi_cdc_meta.v) and the crossing's planted
defects (tb/debug/mut/dmi_cdc_mut_*.v, negative controls of tb/debug/formal/dmi_cdc.toml).
Rerun after any change to rtl/debug/dmi_cdc.v. Each edit must match exactly once and change the
text, or the script stops (2026-11-01: the hand-made copies had drifted from the RTL; DBG-9).
dmi_cdc_mut_dbg6_revert.v is NOT generated: it is the RTL before the DBG-6 fix, kept as it was."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
RTL = "rtl/debug/dmi_cdc.v"
PULSE = "    assign req_pulse_o = armed && (req_s[2] ^ req_s[1]);"
ADOPT = "        else if (adopt_q)               ack_tgl_o <= req_s[1];   // DBG-9: a flop, not a decode\n"
TOGGLE = "        else if (armed && ack_pulse_i)  ack_tgl_o <= ~ack_tgl_o;"

MUTANTS = [
    ("ack_twice", "ack toggled for a request pulse as well as for the DM's done", [
        (TOGGLE, "        else if (armed && (ack_pulse_i || req_pulse_o)) ack_tgl_o <= ~ack_tgl_o;   // MUTANT: ack twice")]),
    ("no_adopt", "adopt-on-reset removed: ack not set to the settled request toggle on re-arm", [
        (ADOPT, "")]),
    ("pulse_stage0", "pulse from the first stage, one before the adoption point (not a metastability model)", [
        (PULSE, "    assign req_pulse_o = armed && (req_s[1] ^ req_s[0]);   // MUTANT: pulse from the first stage")]),
    ("rise_only", "only rising request toggles make a pulse", [
        (PULSE, "    assign req_pulse_o = armed && (req_s[1] & ~req_s[2]);   // MUTANT: only rising toggles")]),
]

META_HEAD = """// =============================================================================
// dmi_cdc_meta.v -- FORMAL ONLY, GENERATED by tb/debug/formal/gen_dmi_cdc_models.py from
// rtl/debug/dmi_cdc.v: the RTL plus metastability injection on the first stage of every
// synchroniser (plan class D1): the request toggle and the ack.
// =============================================================================
"""
META = [
    ("    (* ASYNC_REG = \"TRUE\" *) reg [2:0] req_s;\n",
     """    // D1 (formal only): the first flop of each synchroniser may resolve to the OLD value when
    // its input changed since that clock's previous edge, i.e. take the change one edge late:
    // the logical effect of metastability. Free choices every cycle.
    wire meta_r, meta_a;   // undriven: free
    // the input as it was at this clock's previous edge (a model of the wire, never reset):
    // only a CHANGE since then can be caught late; a stable input is always sampled right
    reg req_in_q = 1'b0, ack_in_q = 1'b0;
    always @(posedge hclk_i) req_in_q  <= req_tgl_i;
    always @(posedge tck_i)  ack_in_q  <= ack_tgl_o;
    (* ASYNC_REG = "TRUE" *) reg [2:0] req_s;
"""),
    ("            req_s <= {req_s[1:0], req_tgl_i};",
     "            req_s <= {req_s[1:0], (meta_r && req_tgl_i != req_in_q) ? req_in_q : req_tgl_i};   // D1: late by one edge"),
    ("        else              ack_s <= {ack_s[0], ack_tgl_o};",
     "        else              ack_s <= {ack_s[0], (meta_a && ack_tgl_o != ack_in_q) ? ack_in_q : ack_tgl_o};  // D1"),
]


def apply(src, edits, what):
    for a, b in edits:
        if src.count(a) != 1:
            sys.exit(f"{what}: edit does not match exactly once in {RTL}: {a.strip()[:60]!r}")
        if a == b:
            sys.exit(f"{what}: the edit changes nothing")
        src = src.replace(a, b)
    return src


def main():
    src = open(os.path.join(ROOT, RTL)).read()
    for name, why, edits in MUTANTS:
        out = f"tb/debug/mut/dmi_cdc_mut_{name}.v"
        open(os.path.join(ROOT, out), "w").write(f"// MUTANT {name} (GENERATED, gen_dmi_cdc_models.py): {why}\n"
                                                 + apply(src, edits, name))
        print("wrote", out)
    out = "tb/debug/formal/dmi_cdc_meta.v"
    open(os.path.join(ROOT, out), "w").write(META_HEAD + apply(src, META, "meta"))
    print("wrote", out)


if __name__ == "__main__":
    main()
